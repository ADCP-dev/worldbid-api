#!/usr/bin/env node

/**
 * generate-ui-components-list.js
 *
 * Scans apps/front/modules/base/ui-app/components/ for .vue files
 * and generates a markdown reference grouped by category folder.
 *
 * Usage: node scripts/generate-ui-components-list.js
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const COMPONENTS_DIR = path.join(
  ROOT,
  "apps",
  "front",
  "modules",
  "base",
  "ui-app",
  "components"
);

const CATEGORY_LABELS = {
  form: "Form Components",
  "data-table": "Data Table",
  "rich-editor": "Rich Editor",
};

const CATEGORY_DESCRIPTIONS = {
  form: "Import from `@base/ui-app/components/form/`",
  "data-table": "Import from `@base/ui-app/components/data-table/`",
  "rich-editor": "Import from `@base/ui-app/components/rich-editor/`",
};

// Component description annotations
const COMPONENT_DESCRIPTIONS = {
  FormInput: "Text input with validation",
  FormTextArea: "Multi-line text area",
  FormSelect: "Dropdown select",
  FormSearchSelect: "Searchable select",
  FormMultipleSelect: "Multi-select dropdown",
  FormDate: "Date picker",
  FormTime: "Time picker",
  FormPassword: "Password input",
  FormSwitch: "Toggle switch",
  FormFile: "File upload",
  FormMultipleFile: "Multiple file upload",
  DataTable: "Main paginated table component with TanStack Vue Table",
  DataTableComboboxFilter: "Searchable combobox column filter",
  DataTableColumnHeader: "Sortable column header with filter",
  SortableHeader: "Sort-only column header",
  EditButton: "Edit action button for table rows",
  ViewButton: "View action button for table rows",
  DeleteButton: "Delete action button for table rows",
  RichEditor: "Tiptap-based rich text editor",
};

function scanComponents(dir) {
  const components = [];

  function walkDir(currentDir, category) {
    const entries = fs.readdirSync(currentDir, { withFileTypes: true });

    for (const entry of entries) {
      const fullPath = path.join(currentDir, entry.name);

      if (entry.isDirectory()) {
        walkDir(fullPath, entry.name);
      } else if (entry.isFile() && entry.name.endsWith(".vue")) {
        const name = path.basename(entry.name, ".vue");
        const importPath = path
          .relative(COMPONENTS_DIR, fullPath)
          .replace(/\\/g, "/");
        components.push({
          name,
          importPath: `@base/ui-app/components/${importPath}`,
          category: category || "other",
        });
      }
    }
  }

  walkDir(dir, null);
  return components;
}

function generateMarkdown(components) {
  // Group by category
  const groups = {};
  for (const comp of components) {
    if (!groups[comp.category]) {
      groups[comp.category] = [];
    }
    groups[comp.category].push(comp);
  }

  const categoryOrder = ["form", "data-table", "rich-editor"];
  const lines = [
    "## UI Components Reference",
    "",
    "> Auto-generated by `scripts/generate-ui-components-list.js`.",
    '> Run `node scripts/generate-ui-components-list.js` to regenerate.',
    "",
  ];

  // Sort categories: known first, then "other"
  const sortedCategories = [
    ...categoryOrder.filter((c) => groups[c]),
    ...Object.keys(groups)
      .filter((c) => !categoryOrder.includes(c))
      .sort(),
  ];

  for (const cat of sortedCategories) {
    const comps = groups[cat];
    if (!comps) continue;

    const label = CATEGORY_LABELS[cat] || cat;
    const desc =
      CATEGORY_DESCRIPTIONS[cat] || `Import from \`@base/ui-app/components/${cat}/\``;

    lines.push(`### ${label}`);
    lines.push("");
    lines.push(`${desc}`);
    lines.push("");

    comps.sort((a, b) => a.name.localeCompare(b.name));

    for (const comp of comps) {
      const descText =
        COMPONENT_DESCRIPTIONS[comp.name] || "Vue component";
      lines.push(`- **${comp.name}** — ${descText} (\`${comp.importPath}\`)`);
    }
    lines.push("");
  }

  // Add utility note
  lines.push("### Notes");
  lines.push("");
  lines.push("- Components share common props: `label`, `error`, `required`, `disabled`, `description`.");
  lines.push("- All form components support `v-model` binding.");
  lines.push("- DataTable filters use `filterType`: `string`, `number`, `date`, `select`, `combobox`, `boolean`.");
  lines.push("- For custom cell renderers, use Vue's `h()` function in the `cell` property.");
  lines.push("");

  return lines.join("\n");
}

function main() {
  if (!fs.existsSync(COMPONENTS_DIR)) {
    console.error(`❌ Components directory not found: ${COMPONENTS_DIR}`);
    process.exit(1);
  }

  const components = scanComponents(COMPONENTS_DIR);
  const markdown = generateMarkdown(components);

  console.log(markdown);
}

main();
